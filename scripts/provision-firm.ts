/**
 * Provisions a new firm instance from one command (Phase 0 acceptance).
 *
 *   pnpm provision-firm \
 *     --slug harlow-vance --legal-name "Harlow & Vance PLLC" --display-name "Harlow & Vance" \
 *     --tier solo --timezone America/Chicago --practice tax,estate --city Plano --state TX \
 *     --owner-name "Avery Harlow" --owner-email avery@harlowvance.example \
 *     --app-url https://harlowvance.lexdesk.app \
 *     (--database-url <empty postgres database> | --local)
 *
 * Steps, each verified before the next:
 *   1. Validate inputs.
 *   2. Confirm the target database holds no firm (never provisions over data).
 *   3. Generate this firm's secrets, or reuse them if a previous run was interrupted.
 *   4. Write .provision/<slug>/: env (0600), render.yaml (per-firm Blueprint), manifest.json.
 *   5. Apply migrations.
 *   6. Bootstrap the firm row and the owner attorney (audited, system principal).
 *   7. Verify: firm slug, audit chain, owner account.
 *   8. Print the owner's one-time setup link and the remaining manual steps.
 *
 * Render resources are created from the rendered Blueprint (see
 * docs/runbooks/provision-firm.md). Calling Render's API directly is deferred
 * until its endpoints are verified against live docs (spec Section 0, rule 4).
 */
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { count, eq } from "drizzle-orm";
import { Client } from "pg";
import { z } from "zod";
import { createDatabase } from "@/db/client";
import { runMigrations } from "@/db/migrate";
import { firmSettings, users } from "@/db/schema";
import { verifyAuditChain } from "@/lib/audit/verify";
import { envSchema, resetEnvCache, TIERS } from "@/lib/env";
import { runBootstrap } from "./lib/firm-bootstrap";

const PRACTICE = ["tax", "business", "estate"] as const;

export const provisionOptionsSchema = z
  .object({
    slug: z
      .string()
      .regex(/^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$/, "slug: lowercase letters, digits, hyphens"),
    legalName: z.string().min(2),
    displayName: z.string().min(2),
    tier: z.enum(TIERS),
    timezone: z.string(),
    practice: z.array(z.enum(PRACTICE)).min(1),
    city: z.string().optional(),
    state: z
      .string()
      .regex(/^[A-Z]{2}$/)
      .optional(),
    ownerName: z.string().min(2),
    ownerEmail: z.email(),
    ownerTitle: z.string().optional(),
    appUrl: z.url(),
    databaseUrl: z.string().optional(),
    local: z.boolean().default(false),
    adminUrl: z.string().default("postgres://postgres:postgres@localhost:5432/postgres"),
    outDir: z.string().default(".provision"),
  })
  .refine((o) => Boolean(o.databaseUrl) !== o.local, {
    message: "Pass exactly one of --database-url or --local",
  });

export type ProvisionOptions = z.input<typeof provisionOptionsSchema>;

export type ProvisionResult = {
  slug: string;
  databaseUrl: string;
  ownerSetupUrl: string;
  outDir: string;
  auditEntries: number;
};

type Log = (line: string) => void;

function generateSecrets() {
  return {
    AUTH_SECRET: randomBytes(48).toString("base64"),
    FIELD_ENCRYPTION_KEY: randomBytes(32).toString("base64"),
    GHL_WEBHOOK_SECRET: randomBytes(32).toString("base64url"),
  };
}

function parseEnvFile(file: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) out[m[1]!] = m[2]!;
  }
  return out;
}

function renderBlueprint(template: string, slug: string): string {
  return template
    .replace(/\blexdesk-(db|web|worker|config)\b/g, `lexdesk-${slug}-$1`)
    .replace(
      /^# LexDesk: Render Blueprint for ONE firm deployment.*$/m,
      `# LexDesk: Render Blueprint for ${slug}. Generated by provision-firm; do not commit.`,
    );
}

function gitCommit(): string | null {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

async function createLocalDatabase(adminUrl: string, slug: string): Promise<string> {
  const name = `lexdesk_${slug.replace(/-/g, "_")}`;
  const admin = new Client({ connectionString: adminUrl });
  await admin.connect();
  try {
    const { rowCount } = await admin.query("SELECT 1 FROM pg_database WHERE datname = $1", [name]);
    if (!rowCount) await admin.query(`CREATE DATABASE "${name}"`);
  } finally {
    await admin.end();
  }
  const u = new URL(adminUrl);
  u.pathname = `/${name}`;
  return u.toString();
}

async function assertNoFirm(databaseUrl: string): Promise<void> {
  const c = new Client({ connectionString: databaseUrl });
  await c.connect();
  try {
    const { rows } = await c.query<{ exists: boolean }>(
      "SELECT to_regclass('public.firm_settings') IS NOT NULL AS exists",
    );
    if (rows[0]?.exists) {
      const r = await c.query("SELECT slug FROM firm_settings LIMIT 1");
      if (r.rowCount)
        throw new Error(
          `Database already belongs to firm "${r.rows[0].slug}". Refusing to provision over it.`,
        );
    }
  } finally {
    await c.end();
  }
}

export async function provisionFirm(
  input: ProvisionOptions,
  log: Log = console.log,
): Promise<ProvisionResult> {
  const o = provisionOptionsSchema.parse(input);
  const step = (n: number, msg: string) => log(`[${n}/8] ${msg}`);

  step(1, `Validating ${o.slug}`);
  // Fail before creating anything if this firm's configuration is invalid.
  const preflight = envSchema.safeParse({
    NODE_ENV: "development",
    FIRM_SLUG: o.slug,
    FIRM_TIER: o.tier,
    FIRM_TIMEZONE: o.timezone,
    APP_URL: o.appUrl,
    DATABASE_URL: o.databaseUrl ?? "postgres://pending",
    ...generateSecrets(),
  });
  if (!preflight.success) {
    throw new Error(
      `Invalid firm configuration: ${preflight.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`,
    );
  }
  const databaseUrl = o.local ? await createLocalDatabase(o.adminUrl, o.slug) : o.databaseUrl!;

  step(2, "Checking the database is empty");
  await assertNoFirm(databaseUrl);

  step(3, "Preparing secrets");
  const dir = path.resolve(o.outDir, o.slug);
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const envFile = path.join(dir, "env");
  const secrets = existsSync(envFile)
    ? (() => {
        const prior = parseEnvFile(envFile);
        log("      reusing secrets from an earlier interrupted run");
        return {
          AUTH_SECRET: prior.AUTH_SECRET!,
          FIELD_ENCRYPTION_KEY: prior.FIELD_ENCRYPTION_KEY!,
          GHL_WEBHOOK_SECRET: prior.GHL_WEBHOOK_SECRET!,
        };
      })()
    : generateSecrets();

  const firmEnv: Record<string, string> = {
    FIRM_SLUG: o.slug,
    FIRM_TIER: o.tier,
    FIRM_TIMEZONE: o.timezone,
    DEMO_MODE: "false",
    APP_URL: o.appUrl,
    DATABASE_URL: databaseUrl,
    ...secrets,
    LOG_LEVEL: "info",
  };

  step(4, `Writing ${path.relative(process.cwd(), dir) || dir}/`);
  const { DATABASE_URL: _db, ...groupEnv } = firmEnv;
  writeFileSync(
    envFile,
    [
      `# ${o.legalName}: environment for Render env group lexdesk-${o.slug}-config`,
      "# SECRET. Do not commit, email or paste into chat. DATABASE_URL comes from the Render database.",
      ...Object.entries(groupEnv).map(([k, v]) => `${k}=${v}`),
      "",
    ].join("\n"),
    { mode: 0o600 },
  );
  writeFileSync(
    path.join(dir, "render.yaml"),
    renderBlueprint(readFileSync(path.join(process.cwd(), "render.yaml"), "utf8"), o.slug),
  );
  writeFileSync(
    path.join(dir, "manifest.json"),
    JSON.stringify(
      {
        slug: o.slug,
        legalName: o.legalName,
        tier: o.tier,
        timezone: o.timezone,
        appUrl: o.appUrl,
        provisionedAt: new Date().toISOString(),
        commit: gitCommit(),
      },
      null,
      2,
    ),
  );

  step(5, "Applying migrations");
  await runMigrations(databaseUrl);

  step(6, "Creating the firm and owner attorney");
  // The command layer reads the firm's identity from the environment.
  Object.assign(process.env, firmEnv);
  resetEnvCache();
  const { db, pool } = createDatabase(databaseUrl, 2);
  try {
    const boot = await runBootstrap(
      db,
      {
        slug: o.slug,
        legalName: o.legalName,
        displayName: o.displayName,
        practiceAreas: o.practice,
        city: o.city,
        state: o.state,
        owner: { name: o.ownerName, email: o.ownerEmail, title: o.ownerTitle },
      },
      "provision-firm",
    );

    step(7, "Verifying");
    const [firm] = await db
      .select({ slug: firmSettings.slug })
      .from(firmSettings)
      .where(eq(firmSettings.id, 1));
    if (firm?.slug !== o.slug) throw new Error("verification failed: firm_settings slug mismatch");
    const [owners] = await db
      .select({ n: count() })
      .from(users)
      .where(eq(users.role, "owner_attorney"));
    if (owners?.n !== 1)
      throw new Error("verification failed: expected exactly one owner attorney");
    const chain = await verifyAuditChain(db);
    if (!chain.ok || chain.checked < 2)
      throw new Error(`verification failed: audit chain ${JSON.stringify(chain)}`);

    step(8, "Done");
    log("");
    log(`Owner setup link for ${o.ownerName} (one-time, expires in 72 hours):`);
    log(`  ${boot.setupUrl}`);
    log("");
    log("Next: create the Render resources from the generated Blueprint and env file.");
    log("      See docs/runbooks/provision-firm.md.");

    return {
      slug: o.slug,
      databaseUrl,
      ownerSetupUrl: boot.setupUrl,
      outDir: dir,
      auditEntries: chain.checked,
    };
  } finally {
    await pool.end();
  }
}

function cli(): ProvisionOptions {
  const { values } = parseArgs({
    options: {
      slug: { type: "string" },
      "legal-name": { type: "string" },
      "display-name": { type: "string" },
      tier: { type: "string" },
      timezone: { type: "string", default: "America/Chicago" },
      practice: { type: "string" },
      city: { type: "string" },
      state: { type: "string" },
      "owner-name": { type: "string" },
      "owner-email": { type: "string" },
      "owner-title": { type: "string" },
      "app-url": { type: "string" },
      "database-url": { type: "string" },
      local: { type: "boolean", default: false },
      "admin-url": { type: "string" },
      out: { type: "string" },
      help: { type: "boolean", default: false },
    },
  });
  if (values.help) {
    console.log(readFileSync(new URL(import.meta.url), "utf8").split("*/")[0]);
    process.exit(0);
  }
  return {
    slug: values.slug ?? "",
    legalName: values["legal-name"] ?? "",
    displayName: values["display-name"] ?? values["legal-name"] ?? "",
    tier: (values.tier ?? "") as "solo",
    timezone: values.timezone ?? "America/Chicago",
    practice: (values.practice ?? "").split(",").filter(Boolean) as (
      "tax" | "business" | "estate"
    )[],
    city: values.city,
    state: values.state,
    ownerName: values["owner-name"] ?? "",
    ownerEmail: values["owner-email"] ?? "",
    ownerTitle: values["owner-title"],
    appUrl: values["app-url"] ?? "",
    databaseUrl: values["database-url"],
    local: values.local ?? false,
    ...(values["admin-url"] ? { adminUrl: values["admin-url"] } : {}),
    ...(values.out ? { outDir: values.out } : {}),
  };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)
) {
  provisionFirm(cli()).catch((err: unknown) => {
    console.error(
      err instanceof z.ZodError
        ? err.issues.map((i) => `${i.path.join(".") || "options"}: ${i.message}`).join("\n")
        : err,
    );
    process.exit(1);
  });
}
